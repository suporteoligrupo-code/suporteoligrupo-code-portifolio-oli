export type MediaKind =
  | "photo"
  | "website"
  | "identity"
  | "logo"
  | "mockup"
  | "social"
  | "editorial"
  | "poster"
  | "campaign";

export type MediaFrameKind = "bleed" | "stage" | "browser" | "logo-stage" | "portrait-stage";

export type MediaOverlay = "none" | "soft" | "cinematic";

export type MediaMotion = "none" | "subtle";

export type MediaTreatment = {
  fit?: "cover" | "contain";
  position?: string;
  scale?: number;
  background?: string;
  inset?: string;
  maxWidth?: string;
  maxHeight?: string;
  frame?: MediaFrameKind;
  overlay?: MediaOverlay;
  motion?: MediaMotion;
  aspectRatio?: string;
  layout?: "feature" | "wide" | "half" | "portrait" | "square" | "strip" | "logo";
  span?: 4 | 5 | 6 | 7 | 8 | 12;
  mobile?: Partial<Omit<MediaTreatment, "mobile">> & {
    src?: string;
    width?: number;
    height?: number;
  };
};

